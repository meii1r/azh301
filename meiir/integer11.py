# Ввод трехзначного числа
num = int(input("Введите трехзначное число: "))

# Извлечение цифр
a = num // 100         # сотни
b = (num // 10) % 10   # десятки
c = num % 10           # единицы

# Сумма и произведение цифр
sum_digits = a + b + c
prod_digits = a * b * c

print("Сумма цифр:", sum_digits)
print("Произведение цифр:", prod_digits)