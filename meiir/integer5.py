# Даны целые положительные числа A и B (A > B).
# На отрезке длины A размещено максимальное количество отрезков длины B (без наложений).
# Используя операцию взятия остатка от деления, найти длину незанятой части отрезка A.

A = int(input("Введите длину отрезка A: "))
B = int(input("Введите длину отрезка B: "))

# Длина незанятой части — это остаток от деления A на B
remaining_length = A % B

print("Длина незанятой части отрезка A:", remaining_length)